function createQuizQuestion() {

  answered = false;

  document
    .getElementById("nextQuestionButton")
    .classList.add("hidden");

  document.getElementById("quizResult").innerText = "";

  const allWords = getAllWords();

  currentQuizWord =
    allWords[
      Math.floor(Math.random() * allWords.length)
    ];

  document.getElementById("quizWord").innerText =
    currentQuizWord.word;

  updateFavoriteButton();

  let options = [currentQuizWord.meaning];

  while (options.length < 4) {

    const randomWord =
      allWords[
        Math.floor(Math.random() * allWords.length)
      ];

    if (!options.includes(randomWord.meaning)) {
      options.push(randomWord.meaning);
    }
  }

  options = shuffleArray(options);

  const optionsContainer =
    document.getElementById("quizOptions");

  optionsContainer.innerHTML = "";

  options.forEach(option => {

    const button =
      document.createElement("button");

    button.innerText = option;

    button.onclick = function() {
      checkQuizAnswer(button, option);
    };

    optionsContainer.appendChild(button);
  });
}

function checkQuizAnswer(button, selectedAnswer) {

  if (answered) {
    return;
  }

  answered = true;

  const buttons =
    document.querySelectorAll(
      "#quizOptions button"
    );

  buttons.forEach(btn => {

    if (
      btn.innerText ===
      currentQuizWord.meaning
    ) {
      btn.classList.add("correct");
    }
  });

  if (
    selectedAnswer ===
    currentQuizWord.meaning
  ) {

    document.getElementById(
      "quizResult"
    ).innerText =
      "🎉 答對啦！這個單字你會了！";

  } else {

    button.classList.add("wrong");

    document.getElementById(
      "quizResult"
    ).innerText =
      "💪 差一點！一起記住這個意思：" +
      currentQuizWord.meaning;
  }

  document
    .getElementById("nextQuestionButton")
    .classList.remove("hidden");
}

function nextQuestion() {
  createQuizQuestion();
}

function shuffleArray(array) {

  for (
    let i = array.length - 1;
    i > 0;
    i--
  ) {

    const j =
      Math.floor(
        Math.random() * (i + 1)
      );

    [array[i], array[j]] =
      [array[j], array[i]];
  }

  return array;
}

