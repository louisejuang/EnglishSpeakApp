function toggleFavorite(current = vocabulary[currentCategory][currentIndex]) {

  if (!current) return;

  const exists =
    favorites.some(
      item =>
        item.word === current.word &&
        item.meaning === current.meaning
    );

  if (exists) {

    favorites =
      favorites.filter(
        item =>
          !(
            item.word === current.word &&
            item.meaning === current.meaning
          )
      );

  } else {

    favorites.push(current);
  }

  localStorage.setItem(
    "favorites",
    JSON.stringify(favorites)
  );

  updateFavoriteButton();
  if (!document.getElementById("favoriteList").classList.contains("hidden")) {
    showFavorites();
  }
}

