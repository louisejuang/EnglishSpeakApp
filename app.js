function normalizeText(text) {

  return text
    .toLowerCase()
    .replace(/[.,!?']/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function checkSpeakingAnswer(spoken) {

  const target =
    speakingSentences[
      speakingIndex
    ].sentence;

  const targetClean =
    normalizeText(target);

  const spokenClean =
    normalizeText(spoken);

  let message = "";

  if (
    targetClean === spokenClean
  ) {

    message =
      "🌟 太棒了！辨識出的句子完全吻合！";

  } else {

    const similarity =
      calculateSimilarity(
        targetClean,
        spokenClean
      );

    if (similarity >= 0.8) {

      message =
        "🙌 很接近囉！再聽一次，把小細節補齊！";

    } else if (similarity >= 0.5) {

      message =
        "🙂 已經抓到一些單字囉！跟著發音再練一次吧！";

    } else {

      message =
        "💪 別急，先聽一次，再慢慢跟著說！";
    }
  }

  document
    .getElementById("spokenResult")
    .innerHTML =
    "<strong>剛剛聽到你說：</strong><br>" +
    spoken +
    "<br><br>" +
    "<strong>一起練的句子：</strong><br>" +
    target +
    "<br><br>" +
    message;
}

function calculateSimilarity(
  target,
  spoken
) {

  const targetWords =
    target.split(" ");

  const spokenWords =
    spoken.split(" ");

  let correctWords = 0;

  targetWords.forEach(word => {

    if (
      spokenWords.includes(word)
    ) {
      correctWords++;
    }

  });

  return (
    correctWords /
    targetWords.length
  );
}

